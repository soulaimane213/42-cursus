#include "libft.h"

char	*ft_strmapi(char const *s, char (*f)(unsigned int, char))
{
	int		i;
	int		string_len;
	char	*result;

	if (!s || !f)
		return (NULL);
	string_len = ft_strlen(s);
	result = (char *)malloc(string_len + 1);
	if (!result)
		return (NULL);
	i = 0;
	while (s[i])
	{
		result[i] = f(i, s[i]);
		i++;
	}
	result[i] = '\0';
	return (result);
}
